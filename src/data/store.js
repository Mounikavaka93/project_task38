export function getProduct(id) {
  return products.find((p) => p.id === id)
}

export function getRelated(product, limit = 4) {
  const same = products.filter((p) => p.id !== product.id && p.category === product.category)
  if (same.length >= limit) return same.slice(0, limit)
  const extra = products.filter((p) => p.id !== product.id && p.category !== product.category)
  return [...same, ...extra].slice(0, limit)
}

export function discountPercent(product, variant) {
  const price = variant?.price ?? product.price
  const original = variant?.originalPrice ?? product.originalPrice
  if (!original || original <= price) return 0
  return Math.round(((original - price) / original) * 100)
}

