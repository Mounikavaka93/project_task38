export function productBadges(product) {
  const set = new Set(product.badges || [])
  if (discountPercent(product) > 0) set.add('sale')
  if (product.bestSeller) set.add('bestseller')
  if (product.isNew) set.add('new')
  if (product.deal || product.flashSale) set.add('deal')
  return ['sale', 'new', 'bestseller', 'deal'].filter((type) => set.has(type))
}
